#!/usr/bin/env node
/**
 * inject-sw-precache.mjs — runs after `vite build` (see apps/workbench `build`).
 *
 * This file is the ONLY source of the shipped service worker (ported from
 * Barsmith's scripts/inject-sw-precache.js). There is deliberately no public/sw.js:
 * a copy there would look authoritative, be the obvious file to edit, and be
 * overwritten by this script a moment later.
 *
 * Why build-time: Vite emits content-hashed bundles (/assets/index-Bx3kQ9aR.js)
 * whose names change every build. A handwritten worker can't know them, so an
 * offline first launch finds the HTML shell but not the JS — the app doesn't boot.
 * This script reads dist/ and writes dist/sw.js with the exact URL list for this
 * build, so the install step caches everything and the app works offline from the
 * first visit on.
 *
 * Cache name = app version + a hash of every precached file's contents, so a new
 * dictionary or bundle always replaces the old cache — even without a version bump.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = fileURLToPath(new URL('../apps/workbench/', import.meta.url));
const DIST = join(APP, 'dist');

// The shell and everything the offline app needs that isn't a hashed asset. Every icon
// the manifest names is here, so installing while offline still finds its artwork.
// og-image.png, privacy.html and licenses.txt are left out: crawlers and occasional
// readers use them, the offline writing loop never does.
const SHELL = [
  '/',
  '/manifest.webmanifest',
  '/icon.svg',
  '/icon-192.png',
  '/icon-512.png',
  '/icon-maskable-512.png',
  '/data/lexicon.txt',
  '/data/definitions.txt',
];
const ASSET_EXT = new Set(['.js', '.css', '.woff2', '.woff', '.png', '.svg', '.webp', '.txt', '.json']);

async function main() {
  const assets = (await readdir(join(DIST, 'assets')))
    .filter((f) => ASSET_EXT.has(extname(f)))
    .map((f) => `/assets/${f}`)
    .sort();
  const urls = [...SHELL, ...assets];

  // Fail the build rather than ship a worker whose install would 404 and abort.
  const hash = createHash('sha256');
  for (const u of urls) {
    const file = join(DIST, u === '/' ? 'index.html' : u);
    try {
      hash.update(u).update(await readFile(file));
    } catch {
      throw new Error(`precache entry ${u} is missing from dist/ (${file})`);
    }
  }
  const pkg = JSON.parse(await readFile(join(APP, 'package.json'), 'utf8'));
  const version = `rhyme-workbench-${pkg.version}-${hash.digest('hex').slice(0, 10)}`;

  const sw = `// ─────────────────────────────────────────────
// SERVICE WORKER — generated by scripts/inject-sw-precache.mjs
// Do not edit by hand; edit that script.
//
// Once Rhyme Workbench has been opened online, the whole app — dictionary,
// definitions, every tool — works with no connection.
//
//   Precached URLs  — cache-first. Installed up front, replaced wholesale when a new
//                     build ships (the cache name changes with the build's contents).
//   Navigations     — network-first so a new release is picked up; offline, the cached
//                     app shell. Only the app itself is ever stored as the shell.
//   Other same-origin GETs — stale-while-revalidate.
// ─────────────────────────────────────────────

const CACHE_VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const PRECACHED = new Set(PRECACHE);

self.addEventListener('install', (event) => {
  // No catch: a failed addAll must abort the install. A partial cache that activated
  // would serve a broken offline app — better to keep the previous worker and retry.
  event.waitUntil(caches.open(CACHE_VERSION).then((cache) => cache.addAll(PRECACHE)));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Only the app may be stored as the offline shell. Caching every navigation under
    // '/' would let the privacy page become what an offline launch opens (Barsmith hit
    // exactly this when it added its second page).
    const isAppShell = url.pathname === '/' || url.pathname === '/index.html';
    event.respondWith(
      fetch(request)
        .then((res) => {
          if (isAppShell && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put('/', copy)).catch(() => {});
          }
          return res;
        })
        .catch(() => caches.match(request).then((hit) => hit || caches.match('/'))),
    );
    return;
  }

  if (PRECACHED.has(url.pathname)) {
    event.respondWith(caches.match(url.pathname).then((hit) => hit || fetch(request)));
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put(request, copy)).catch(() => {});
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    }),
  );
});
`;
  await writeFile(join(DIST, 'sw.js'), sw, 'utf8');
  console.log(`[inject-sw-precache] dist/sw.js — ${urls.length} URLs precached (${version})`);
}

main().catch((e) => {
  console.error('[inject-sw-precache]', e.message || e);
  process.exit(1);
});
